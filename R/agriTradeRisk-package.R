#' agriTradeRisk: Agricultural Export Competitiveness and Risk Analysis
#'
#' An integrated workflow for horticultural export competitiveness, risk and
#' market diversification.
#'
#' * [export_concentration()] - destination or product concentration.
#' * [competitiveness_index()] - revealed comparative advantage, world
#'   market share and relative unit values.
#' * [cms_decomposition()] - constant market share decomposition of export
#'   growth.
#' * [price_transmission()] - cointegration and error correction between
#'   export and domestic prices.
#' * [exchange_rate_exposure()] - currency risk of the export portfolio.
#' * [market_entry_risk()] - composite entry-risk scores for destinations.
#' * [market_diversification()] - mean-variance optimal destination mix.
#'
#' Example data sets [hort_exports], [trade_totals], [fx_rates] and
#' [grape_prices] are simulated for illustration and are not official trade
#' statistics.
#'
